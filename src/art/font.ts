type Mark = 'acute' | 'dot' | 'ogonek';
const COMPOSED: Record<string, [string, Mark]> = {
  Ą: ['A', 'ogonek'], Ę: ['E', 'ogonek'], Ć: ['C', 'acute'], Ń: ['N', 'acute'], Ó: ['O', 'acute'],
  Ś: ['S', 'acute'], Ź: ['Z', 'acute'], Ż: ['Z', 'dot'],
  ą: ['a', 'ogonek'], ę: ['e', 'ogonek'], ć: ['c', 'acute'], ń: ['n', 'acute'], ó: ['o', 'acute'],
  ś: ['s', 'acute'], ź: ['z', 'acute'], ż: ['z', 'dot'],
};

interface Glyph {
  w: number;
  /** [x, y] pixels; y is relative to the cap line (may be negative for accents). */
  px: [number, number][];
}

const glyphs = new Map<string, Glyph>();

function build(ch: string): Glyph | null {
  const comp = COMPOSED[ch];
  const rows = G[comp ? comp[0] : ch];
  if (!rows) return null;
  const w = Math.max(...rows.map((r) => r.length));
  const px: [number, number][] = [];
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) if (r[x] === '#') px.push([x, y]);
  });
  if (comp) {
    const upper = comp[0] === comp[0].toUpperCase();
    const mid = Math.floor((w - 1) / 2);
    // Capitals start at row 0, small letters at row 2. Small letters keep one clear row under the mark.
    const top = upper ? -1 : 0;
    if (comp[1] === 'acute') px.push([mid + 1, top - 1], [mid, top]);
    else if (comp[1] === 'dot') px.push([mid, upper ? -2 : 0]);
    else px.push([w - 2, 7], [w - 1, 8]);
  }
  return { w, px };
}

function glyph(ch: string): Glyph | null {
  let g = glyphs.get(ch);
  if (g === undefined) {
    g = build(ch) ?? undefined;
    if (g) glyphs.set(ch, g);
  }
  return g ?? null;
}

export function measure(text: string): number {
  let w = 0;
  for (const ch of text) {
    if (ch === ' ') w += FONT.space + FONT.tracking;
    else {
      const g = glyph(ch) ?? glyph('?')!;
      w += g.w + FONT.tracking;
    }
  }
  return Math.max(0, w - FONT.tracking);
}

/** Draws one line. (x, y) is the top-left of the line box. */
export function drawText(buf: PixelBuffer, text: string, x: number, y: number, color: Color, shadow?: Color): void {
  const pass = (ox: number, oy: number, c: Color): void => {
    let cx = x + ox;
    for (const ch of text) {
      if (ch === ' ') { cx += FONT.space + FONT.tracking; continue; }
      const g = glyph(ch) ?? glyph('?')!;
      for (const [gx, gy] of g.px) buf.set(cx + gx, y + oy + 2 + gy, c);
      cx += g.w + FONT.tracking;
    }
  };
  if (shadow !== undefined) pass(0, 1, shadow);
  pass(0, 0, color);
}

/** Greedy word wrap to a pixel width. Honors '\n'. */
export function wrap(text: string, maxWidth: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const test = line ? `${line} ${word}` : word;
      if (line && measure(test) > maxWidth) {
        out.push(line);
        line = word;
      } else line = test;
    }
    out.push(line);
  }
  return out;
}

export interface TextStyle {
  color: Color;
  shadow?: Color;
  align?: 'left' | 'center' | 'right';
  maxWidth?: number;
  lineHeight?: number;
}

/** Renders (wrapped) text into a fresh buffer that fits it exactly. */
export function renderText(text: string, style: TextStyle): PixelBuffer {
  const lines = style.maxWidth ? wrap(text, style.maxWidth) : text.split('\n');
  const lh = style.lineHeight ?? FONT.lineHeight;
  const w = Math.max(1, ...lines.map(measure));
  const buf = new PixelBuffer(w, lines.length * lh + 1);
  lines.forEach((line, i) => {
    const lw = measure(line);
    const x = style.align === 'center' ? Math.floor((w - lw) / 2) : style.align === 'right' ? w - lw : 0;
    drawText(buf, line, x, i * lh, style.color, style.shadow);
  });
  return buf;
}
